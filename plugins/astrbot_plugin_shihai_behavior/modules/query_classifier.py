"""query 分类：判断这一轮要不要注入「这些天的片段」时间线块。

只看用户这句话的字面，不读任何记忆状态——不改 schema、不改衰减、不碰存储。
它只是检索权限的开关，不参与排序，也不改变动力学。

为什么需要它（真实语料实测，2026-11-11）：
  - 466 条情景事件里回溯词的分布：后来58 之前26 那天24 当时23 说过20
    哪天17 想起17 那会儿16 昨天10 上次7 前天6 一开始5 还记得4
    什么时候3 提过3；那次2 上回2 前几1 早先1 记得吗1
  - 190 条入站消息里，含回溯表达的只有 2 条（1.1%）。也就是说原来"每轮
    都带时间线"的做法，98% 的时候只是把两百多字的背景塞进 prompt，还常被
    她当成话题说出来——09:52 用户只发了一个「?」，她回「昨天那事，昨天已经
    翻篇了」，正是因为那轮她手上唯一的素材就是这块时间线。

词表取舍：
  - 不收「后来」「一开始」「早先」：它们是叙事连接词（"后来我就走了"），
    日常句子里到处都是，误触发率高，收了等于没按需。
  - 频次低但语义明确的（那次 / 上回 / 前几 / 记得吗）保留：漏给时间线的
    代价（她答不上"哪天"）比多给几行 token 更大。
"""

from __future__ import annotations

# 时间指示词：明确指向"过去某一天 / 某一段"
_TIME_WORDS: tuple[str, ...] = (
    "昨天", "前天", "上周", "上个月", "前几",
    "那天", "哪天", "上次", "那次", "上回",
    "之前", "那会儿", "当时", "什么时候", "几号",
)

# 记忆动词：明确在要求"回忆"
_RECALL_VERBS: tuple[str, ...] = (
    "还记得", "记得吗", "想起", "提过", "说过",
)

RECALL_KEYWORDS: tuple[str, ...] = _TIME_WORDS + _RECALL_VERBS


def needs_timeline(query: str) -> bool:
    """这一轮要不要带时间线块。

    空 query（纯图片 / 语音消息）返回 False：这时候她该说眼前的东西，
    不该被一块与当前无关的"日子底子"带走。
    """
    q = str(query or "").strip()
    if not q:
        return False
    return any(kw in q for kw in RECALL_KEYWORDS)
