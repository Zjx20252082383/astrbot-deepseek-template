"""隐私追问门：在 LLM 之前判定"这句话在问什么"，并按问题性质给不同回答。

## 为什么必须在 LLM 之前

「鑫鑫胃还疼吗」和「你没跟他们说吧」在字面上都不是"敏感词"，但都在问隐私。
模型不知道一个本地事实——**私聊记忆根本没进群聊上下文，"说出去"从未发生**——
所以它要么顺着话头编，要么把私聊内容当常识答出去。

判定和事实都在本地，模型只负责把这句结论说成人话。

## 默认拦截，不是列安全清单

旧版错误：列一份"放过"的词表（今天吃什么 / 胃还疼吗）。
「胃还疼吗」就是隐私追问——答"好多了昨天去看医生"等于在群里公开就医信息；
答"我不知道"又暴露"她不知道这件事"。

**群聊里凡是涉及主人状况的问题，一律进门。**

## 三个分档

1. `confirm` 确认是否泄露（"你没跟他们说吧"）
   → **可以诚实答"没有"**。私聊记忆确实没进群聊上下文，这是系统里唯一
     能对隐私问题说真话的场景，既真话又确认了安全。
2. `content` 询问隐私内容（"鑫鑫胃还疼吗"）
   → 模糊化 + 转移。可以承认"有点不舒服"，但不说症状、时间、医院、程度。
3. `fake` 假装已知来套取确认（"鑫鑫胃镜是几点来着"）
   → 反问来源。"听谁说的呀？" 不确认也不否认。
4. `safe` 与主人无关（"你也喜欢这首歌吗"）
   → 不注入。
"""

from __future__ import annotations

import re
from typing import Optional

OWNER_TOKENS = ("鑫鑫", "冰裂纹的熵", "郑俊鑫", "俊鑫", "他", "她")

# 确认是否泄露
_CONFIRM = (
    r"你(有)?没(有)?(跟|和|对).{0,8}(说|讲|提)",
    r"你(有)?没(有)?(告诉|告知)",
    r"你(有)?没(有)?(说出去|讲出去|传出去|泄露|漏出去)",
    r"(跟|和).{0,6}(说|讲)(了|过).{0,4}(吗|么|吧)",
    r"(别人|他们|其他人|旁人|外人).{0,8}(知道|晓得|听说)",
    r"(他|她|他们).{0,4}(知道|晓得).{0,4}(吗|么|吧)",
    r"(保密|守口|嘴严|嘴紧)",
    r"(还)?有?谁(知道|晓得)",
)

# 假装已知：细节型问句，答了就等于确认
_FAKE = (
    r"(几点|哪天|什么时候|多久|第几次).{0,6}(去|做|检|看|吃)",
    r"(是|在)(哪家|哪个)(医院|诊所|科室)",
    r"(胃镜|CT|化验|检查|开药).{0,6}(几点|哪天|结果|报告)",
    r"(是不是|有没有).{0,6}(去过|做了|吃了|看了)",
)

# 询问主人状况的"强词"：单独出现就足以判定在问主人
_CONTENT_BODY = (
    "胃", "肚子", "牙疼", "发烧", "感冒", "不舒服", "病了", "病好",
    "医院", "医生", "检查", "吃药", "手术", "住院", "体检", "胃镜",
    "心情", "情绪", "难过", "失眠", "睡不着", "熬夜",
    "还好吗", "好点没", "好多了吗", "没事吧", "怎么样",
)

# 弱词：只有和主人主体一起出现时才算，"今天吃什么"不能因为一个"吃"就被拦
_ACTIVITY = (
    "吃", "睡", "加班", "考试", "面试", "答辩", "上班", "上课", "课",
    "累", "困", "开心", "疼", "头",
)

_CONFIRM_RE = re.compile("|".join(_CONFIRM))
_FAKE_RE = re.compile("|".join(_FAKE))


def classify(text: str, viewer_is_owner: bool = False) -> str:
    """返回 confirm / fake / content / safe。"""
    s = str(text or "")
    if not s or viewer_is_owner:
        return "safe"
    if _CONFIRM_RE.search(s):
        return "confirm"
    has_owner = any(t in s for t in OWNER_TOKENS)
    if _FAKE_RE.search(s) and has_owner:
        return "fake"
    if has_owner and (any(b in s for b in _CONTENT_BODY)
                      or any(b in s for b in _ACTIVITY)):
        return "content"
    # 省略主语的强词（"胃还疼吗""好点没"）—— 群里默认就是在问主人。
    # 只认强词：弱词省主语时更可能在问对方自己（"今天吃什么"）。
    if any(b in s for b in _CONTENT_BODY):
        return "content"
    return "safe"


_TEMPLATE = {
    "confirm": (
        "（本地事实：这段私聊内容从未出现在任何群聊或其他人的对话里。"
        "如实答「没有」，可以加一句「这是我和鑫鑫之间的事」。"
        "不要顺着话头承认，也不要编造说给过谁。这是唯一可以诚实肯定的场景。）"
    ),
    "content": (
        "（本地事实：这条内容属于私聊范围，不能在这里展开。"
        "可以承认「他最近是有点不舒服」，但不说症状、时间、医院、程度、检查结果；"
        "说完立刻把话头转给对方（「你最近怎么样」）。不要答「我不知道」，"
        "那等于暴露你并不知情。）"
    ),
    "fake": (
        "（本地事实：对方在假装已经知道细节来套你确认。"
        "反问来源（「听谁说的呀」），不确认、不否认、不补细节。"
        "不要顺着说「对，就是那家」——那等于替对方坐实了传闻。）"
    ),
}


def guard(text: str, viewer_is_owner: bool = False) -> Optional[str]:
    """返回要注入 prompt 的一行；safe 返回 None。"""
    tier = classify(text, viewer_is_owner)
    return _TEMPLATE.get(tier)
